export function translate(text, language = 'en') {
  if (language === 'en' || !languages.includes(language)) return text;
  const index = language === 'zh-TW' ? 1 : 0;
  if (strings[text]) return strings[text][index];
  const patterns = [
    [/^DAY (\d+)$/, n => `第 ${n} 天`],
    [/^(\d+) little adventures planned$/, n => index ? `已規劃 ${n} 個活動` : `已规划 ${n} 个活动`],
    [/^Drag to reorder · All times in (.+)$/, zone => index ? `拖曳以排序 · 時區：${zone}` : `拖动以排序 · 时区：${zone}`],
    [/^(.+) · (\d+) days?$/, (place,n) => `${translate(place,language)} · ${n} 天`],
    [/^(.*) is ready\. Save to apply it\.$/, name => index ? `${name} 已就緒，儲存後套用。` : `${name} 已就绪，保存后应用。`],
    [/^Day (\d+)$/, n => `第 ${n} 天`],
    [/^All times: (.+)$/, zone => index ? `所有時間：${zone}` : `所有时间：${zone}`],
    [/^A little adventure in (.+)$/, place => `${translate(place,language)} · 一段小小的冒險`.replace('冒險',index?'冒險':'冒险')],
    [/^(\d+) of (\d+)$/, (a,b) => `第 ${a} / ${b} 步`],
    [/^(.*) · (\d+) activities$/, (date,n) => `${date} · ${n} ${index?'個活動':'个活动'}`],
    [/^Check (.+): .* up to (\d+) characters is required\.$/, (field,max) => `${index?'請檢查':'请检查'}${translate(field,language)}：${index?'請填寫有效文字，最多':'请填写有效文字，最多'} ${max} ${index?'個字元':'个字符'}。`],
  ];
  for (const [pattern, format] of patterns) { const match = text.match(pattern); if (match) return format(...match.slice(1)); }
  if (text.includes(' · ')) return text.split(' · ').map(part => translate(part,language)).join(' · ');
  return text;
}
const privateText = '[data-user-content], textarea, script, style, .current-trip strong, .page-heading h1, .hero-banner p, .activity-body h3, .activity-body>p, .place-link, .trip-meta>span:last-child';
export function localizeUI(root, language) {
  if (language === 'en') return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = []; while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) {
    if (node.parentElement?.closest(privateText)) continue;
    const source = node.textContent.trim();
    if (source) node.textContent = node.textContent.replace(source, translate(source,language));
  }
  for (const element of root.querySelectorAll('[placeholder], [aria-label], [title], img[alt]')) {
    for (const attr of ['placeholder','aria-label','title','alt']) if (element.hasAttribute(attr)) element.setAttribute(attr, translate(element.getAttribute(attr),language));
  }
}
